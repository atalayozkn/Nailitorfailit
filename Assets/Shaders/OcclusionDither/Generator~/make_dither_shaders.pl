#!/usr/bin/perl
# Generates occlusion-dither copies of URP Lit / Simple Lit and Unity Toon (URP subshader only).
# Usage: perl make_dither_shaders.pl <urpShadersDir> <toonShadersDir> <outDir>
use strict; use warnings;
my ($urp, $toon, $out) = @ARGV;
my $INC = '#include "Assets/Shaders/OcclusionDither/OcclusionDither.hlsl"';
my $HEADER = "// GENERATED by make_dither_shaders.pl from the installed package shader - regenerate after package upgrades.\n"
           . "// Same as the original, plus OcclusionDitherClip() in the color / depth passes (shadows untouched).\n";

sub slurp { my $f = shift; open my $h, '<:raw', $f or die "$f: $!"; local $/; my $t = <$h>; close $h; $t =~ s/\r\n/\n/g; $t }
sub spew  { my ($f, $t) = @_; $t =~ s/\n/\r\n/g; open my $h, '>:raw', $f or die "$f: $!"; print $h $t; close $h; print "wrote $f\n" }

# Wrapper templates. FN = original fragment, POS = SV_POSITION field.
my %wrap = (
  forward_uint => sub { my ($fn,$pos,$in,$out)=@_; <<"E" },
void ${fn}_Dither($in input, out half4 outColor : SV_Target0
#ifdef _WRITE_RENDERING_LAYERS
    , out uint outRenderingLayers : SV_Target1
#endif
)
{
    OcclusionDitherClip(input.$pos);
    $fn(input, outColor
#ifdef _WRITE_RENDERING_LAYERS
        , outRenderingLayers
#endif
    );
}
E
  depthnormals => sub { my ($fn,$pos,$in)=@_; <<"E" },
void ${fn}_Dither($in input, out half4 outNormalWS : SV_Target0
#ifdef _WRITE_RENDERING_LAYERS
    , out uint outRenderingLayers : SV_Target1
#endif
)
{
    OcclusionDitherClip(input.$pos);
    $fn(input, outNormalWS
#ifdef _WRITE_RENDERING_LAYERS
        , outRenderingLayers
#endif
    );
}
E
  depthonly => sub { my ($fn,$pos,$in)=@_; <<"E" },
half ${fn}_Dither($in input) : SV_TARGET
{
    OcclusionDitherClip(input.$pos);
    return $fn(input);
}
E
  toon_forward => sub { my ($fn,$pos,$in)=@_; <<"E" },
void ${fn}_Dither($in i, out float4 finalRGBA : SV_Target0
#ifdef _WRITE_RENDERING_LAYERS
    , out float4 outRenderingLayers : SV_Target1
#endif
)
{
    OcclusionDitherClip(i.$pos);
    $fn(i, finalRGBA
#ifdef _WRITE_RENDERING_LAYERS
        , outRenderingLayers
#endif
    );
}
E
  toon_outline => sub { my ($fn,$pos,$in)=@_; <<"E" },
float4 ${fn}_Dither($in i) : SV_Target
{
    OcclusionDitherClip(i.$pos);
    return $fn(i);
}
E
);

# include file (last path part) => [template, input struct, position field]
my %passes = (
  'LitForwardPass.hlsl'          => ['forward_uint', 'Varyings', 'positionCS'],
  'SimpleLitForwardPass.hlsl'    => ['forward_uint', 'Varyings', 'positionCS'],
  'DepthOnlyPass.hlsl'           => ['depthonly',    'Varyings', 'positionCS'],
  'LitDepthNormalsPass.hlsl'     => ['depthnormals', 'Varyings', 'positionCS'],
  'SimpleLitDepthNormalsPass.hlsl' => ['depthnormals', 'Varyings', 'positionCS'],
  'DepthNormalsPass.hlsl'        => ['depthnormals', 'Varyings', 'positionCS'],
  'UniversalToonBody.hlsl'       => ['toon_forward', 'VertexOutput', 'pos'],
  'UniversalToonOutline.hlsl'    => ['toon_outline', 'VertexOutput', 'pos'],
);

# Toon forward also includes LitForwardPass.hlsl, so toon files must be checked first.
my @order = qw(UniversalToonBody.hlsl UniversalToonOutline.hlsl LitForwardPass.hlsl SimpleLitForwardPass.hlsl DepthOnlyPass.hlsl LitDepthNormalsPass.hlsl SimpleLitDepthNormalsPass.hlsl DepthNormalsPass.hlsl);

sub patch_programs {
    my $text = shift; my $count = 0;
    $text =~ s{(HLSLPROGRAM\n)(.*?)(\n[ \t]*ENDHLSL)}{
        my ($open, $body, $close) = ($1, $2, $3);
        for my $file (@order) {
            # Must be the pass's last real include (the one defining the fragment).
            next unless $body =~ /^([ \t]*)#include "[^"]*\/\Q$file\E"[^\n]*$/m;
            my $indent = $1;
            my ($fn) = $body =~ /^[ \t]*#pragma fragment (\w+)/m or die "no fragment pragma for $file";
            my ($tpl, $in, $pos) = @{$passes{$file}};
            $body =~ s/^([ \t]*#pragma fragment )\Q$fn\E\b/$1${fn}_Dither/m;
            my $w = $wrap{$tpl}->($fn, $pos, $in);
            $body =~ s{(^[ \t]*#include "[^"]*/\Q$file\E"[^\n]*)(?:\n|\z)}{$1\n\n$indent$INC\n$w}m
                or die "include not found for $file";
            $count++;
            last;
        }
        "$open$body$close";
    }gse;
    return ($text, $count);
}

# --- URP Lit / Simple Lit ---
for my $pair (['Lit', 'Universal Render Pipeline/Lit'], ['SimpleLit', 'Universal Render Pipeline/Simple Lit']) {
    my ($file, $name) = @$pair;
    my $t = slurp("$urp/$file.shader");
    $t =~ s/^Shader "\Q$name\E"/Shader "Hidden\/OcclusionDither\/$file"/m or die "name not found in $file";
    my $n; ($t, $n) = patch_programs($t);
    print "$file: patched $n passes\n";
    spew("$out/${file}Dither.shader", $HEADER . $t);
}

# --- Unity Toon: Properties + URP subshader only ---
{
    my $t = slurp("$toon/UnityToon.shader");
    my $propsEnd = index($t, "    // *************************** //\n    // ****** HDRP Subshader");
    my $urpStart = index($t, "    // *************************** //\n    // ****** URP Subshader");
    my $legacy   = index($t, "    // ***************************** //\n    // ****** Legacy Subshader");
    die "toon markers not found" if $propsEnd < 0 || $urpStart < 0 || $legacy < 0;
    my ($editor) = $t =~ /^([ \t]*CustomEditor "[^"]+"\n)/m;
    my $s = substr($t, 0, $propsEnd) . substr($t, $urpStart, $legacy - $urpStart) . ($editor // '') . "}\n";
    $s =~ s/^Shader "Toon\/Toon"/Shader "Hidden\/OcclusionDither\/Toon"/m or die "toon name not found";
    $s =~ s{#include(_with_pragmas)? "URP/}{'#include' . ($1 // '') . ' "Packages/com.unity.toonshader/Runtime/Shaders/URP/'}ge;
    my $n; ($s, $n) = patch_programs($s);
    print "Toon: patched $n passes\n";
    spew("$out/ToonDither.shader", $HEADER . $s);
}
